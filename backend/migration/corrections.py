"""
Реестр известных исправлений данных («оплошности оператора»).

Каждое исправление — это деньги, которые ДОЛЖНЫ быть учтены, но в листе введены
так, что формула их не посчитала (напр. число текстом '52 250'). Аудитор
(migration/audit.py) находит такие ячейки; здесь мы фиксируем верное значение.

Самоотключение: исправление применяется ТОЛЬКО пока в листе на этом месте ещё
жива аномалия (текст вместо числа). Как только оператор исправит ячейку в
источнике (введёт числом), формула посчитает сама, аномалия исчезнет — и
исправление перестанет применяться, без риска двойного счёта.

Полный человекочитаемый список — docs/data-anomalies.md.
"""

# key — нормализованное имя водителя (lower); date — ISO; amount — верная сумма.
CORRECTIONS = [
    {
        'key': 'каменский', 'year': 2026, 'month': 1,
        'date': '2026-01-28', 'amount': 52250.0,
        'cell': 'AW34',
        'note': "исправление: в листе введено текстом '52 250' (AW34) — формула не учла",
    },
]


def effective(anomalies):
    """Исправления, у которых в листе ещё есть соответствующая аномалия.

    Сопоставляем по (водитель, период, дата, сумма) — точное совпадение, чтобы
    не применить исправление к уже исправленной ячейке.
    """
    live = {(a['key'], a['period'], a['date'], round(a['parsed'], 2)) for a in anomalies}
    out = []
    for c in CORRECTIONS:
        period = f"{c['year']}-{c['month']:02d}"
        if (c['key'], period, c['date'], round(c['amount'], 2)) in live:
            out.append(c)
    return out
